	("111","0000",'0','0','0','0','0'),-- 011010 NOT OR1
	("110","0010",'0','0','0','0','0'),-- 011011 EOR1
	("101","0010",'0','0','0','0','0'),-- 011100 NOTC (C ^ 1)
	("110","0110",'0','0','0','0','0'),-- 011101 XCN
	("110","1100",'0','0','0','1','0'),-- 011110 DAA
	("110","1101",'0','0','0','1','0'),-- 011111 DAS
	("110","1110",'0','0','0','0','0'),-- 100000 MUL
	("110","1111",'1','1','0','0','0') -- 100001 DIV
	);

	type RegCtrl_t is array(0 to 18) of RegCtrl_r;
	constant  REG_TAB: RegCtrl_t := (
	("000","00","000","00"),--00000
	("001","00","000","00"),--00001 PC++
	("001","00","001","00"),--00010 PC++, Flags
	("000","00","001","00"),--00011 Flags
	("000","11","000","00"),--00100 X->SP
	("001","00","000","01"),--00101 [PC]->T, PC++
	("000","00","000","01"),--00110 []->T
	("000","00","001","10"),--00111 ALU()->T, Flags
	("000","00","100","00"),--01000 CLR/SET
	("011","00","000","00"),--01001 PC+DR->PC
	("000","00","101","00"),--01010 C change
	("000","00","000","10"),--01011 ALU()->T
	("010","00","000","00"),--01100 []:DR->PC
	("000","10","000","00"),--01101 Reg->[SP], SP--
	("100","00","000","00"),--01110 AX->PC
	("000","00","010","00"),--01111 1->B
	("000","01","000","00"),--10000 SP++
	("000","00","011","00"),--10001 []->PSW
	("101","00","000","00") --10010 FF:AL->PC
	);

	function to_microinst(data : std_logic_vector(31 downto 0)) return MicroInst_r is
		variable result : MicroInst_r;
	begin
		result.stateCtrl := data(31 downto 30);
		result.addrBus	 := data(29 downto 28);
		result.addrCtrl  := data(27 downto 22);
		result.regMode	 := data(21 downto 17);
		result.regAXY	 := data(16 downto 15);
		result.busCtrl	 := data(14 downto 9);
		result.ALUCtrl	 := data(8 downto 3);
		result.outBus	 := data(2 downto 0);
		return result;
	end function;

	signal MI	: MicroInst_r;
	signal ALUFlags	: ALUCtrl_r;
	signal R	: RegCtrl_r;

	signal ADDR	: unsigned(10 downto 0);
	signal NEXT_ADDR	: unsigned(10 downto 0);
	signal RST_ADDR	: unsigned(10 downto 0);
	signal RST_VALUE : std_logic_vector(31 downto 0);

	attribute syn_keep : boolean;
	attribute syn_keep of RST_ADDR: signal is true;

begin
	RST_ADDR <= to_unsigned(0, RST_ADDR'length);
	RST_VALUE <= "00000000000000100000000000000000";

	NEXT_ADDR <= RST_ADDR when RST_N = '0' else
				 to_unsigned(4 + to_integer(STATE(1 downto 0)), ADDR'length) when IR = x"9E" and STATE(3) = '1' else -- DIV
				 to_unsigned(3, ADDR'length) when IR = x"CF" and STATE(3) = '1' else -- MUL
				 unsigned(IR) & STATE(2 downto 0);

	gen_lattice : if VENDOR = VENDOR_LATTICE generate
		process(CLK)
		begin
			if rising_edge(CLK) then
				if EN = '1' or RST_N = '0' then
					ADDR <= NEXT_ADDR;

					if RST_N = '0' then
						-- Lattice needs this to infer BRAM for ROM
						M_TAB(to_integer(NEXT_ADDR)) <= RST_VALUE;
					end if;
				end if;
			end if;
		end process;
	end generate;

	gen_other : if VENDOR /= VENDOR_LATTICE generate
		process(CLK)
		begin
			if rising_edge(CLK) then
				if EN = '1' or RST_N = '0' then
					ADDR <= NEXT_ADDR;
				end if;
			end if;
		end process;
	end generate;

	MI <= to_microinst(M_TAB(to_integer(ADDR)));

	ALUFlags <= ALU_TAB(to_integer(unsigned(MI.ALUCtrl)));
	R <= REG_TAB(to_integer(unsigned(MI.regMode)));

	M <= (ALUFlags,
			MI.stateCtrl,
			MI.addrBus,
			MI.addrCtrl,
			R.loadPC,
			R.loadSP,
			MI.regAXY,
			R.loadP,
			R.loadT,
			MI.busCtrl,
			MI.outBus);

end rtl;
