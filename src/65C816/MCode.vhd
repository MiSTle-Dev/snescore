	function to_microinst(data : std_logic_vector(52 downto 0)) return MicroInst_r is
		variable result : MicroInst_r;
	begin
		result.stateCtrl := data(52 downto 50);
		result.addrBus	 := data(49 downto 46);
		result.addrInc	 := data(45 downto 44);
		result.loadP	 := data(43 downto 41);
		result.loadT	 := data(40 downto 39);
		result.muxCtrl	 := data(38 downto 37);
		result.addrCtrl  := data(36 downto 29);
		result.loadPC	 := data(28 downto 26);
		result.loadSP	 := data(25 downto 23);
		result.regAXY	 := data(22 downto 20);
		result.loadDKB	 := data(19 downto 18);
		result.busCtrl	 := data(17 downto 12);
		result.ALUCtrl	 := data(11 downto 7);
		result.byteSel	 := data(6 downto 5);
		result.outBus	 := data(4 downto 2);
		result.va		 := data(1 downto 0);
		return result;
	end function;

	signal MI			: MicroInst_r;
	signal ALUFlags	: ALUCtrl_r;

	signal ADDR : unsigned(10 downto 0);
	signal NEXT_ADDR : unsigned(10 downto 0);
	signal RST_ADDR : unsigned(10 downto 0);
	signal RST_VALUE : std_logic_vector(52 downto 0);

	signal STATE2 : unsigned(3 downto 0);

	attribute syn_keep : boolean;
	attribute syn_keep of RST_ADDR: signal is true;
begin
	RST_ADDR <= to_unsigned(2047, RST_ADDR'length);
	RST_VALUE <= "00000000000000000000000000100000000000000000000000011";

	STATE2 <= STATE - 1;
	NEXT_ADDR <= RST_ADDR when RST_N = '0' or STATE = "0000" else
				 unsigned(IR) & STATE2(2 downto 0);

	gen_lattice : if VENDOR = VENDOR_LATTICE generate
		process(CLK)
		begin
			if rising_edge(CLK) then
				if EN = '1' or RST_N = '0' then
					ADDR <= NEXT_ADDR;

					if RST_N = '0' then
						-- Lattice needs this to infer BRAM for ROM
						M_TAB(to_integer(NEXT_ADDR)) <= RST_VALUE;
					end if;
				end if;
			end if;
		end process;
	end generate;

	gen_other : if VENDOR /= VENDOR_LATTICE generate
		process(CLK)
		begin
			if rising_edge(CLK) then
				if EN = '1' or RST_N = '0' then
					ADDR <= NEXT_ADDR;
				end if;
			end if;
		end process;
	end generate;

	MI <= to_microinst(M_TAB(to_integer(ADDR)));

	ALUFlags <= ALU_TAB(to_integer(unsigned(MI.ALUCtrl)));

	M <= (ALUFlags, MI.stateCtrl, MI.addrBus, MI.addrInc, MI.muxCtrl, MI.addrCtrl, MI.loadPC, MI.loadSP,
			MI.regAXY, MI.loadP, MI.loadT, MI.loadDKB, MI.busCtrl, MI.byteSel, MI.outBus, MI.va);

end rtl;
